/**
 * Adapta dinamicamente qualquer dia de matriz para o Local (Academia / Casa / Híbrido)
 * e Nível (Iniciante / Intermediário / Atleta Pro com FST-7, Rest-Pause, Drop-Set, RPE 9-10).
 */
export function buildAdaptiveWorkout(matrixId, dayIndex, location = 'gym', level = 'intermediate', loadHistory = {}) {
  const matrix = getMatrixById(matrixId);
  const safeDayIndex = Math.max(0, Math.min(dayIndex, matrix.days.length - 1));
  const day = matrix.days[safeDayIndex];

  const exercises = day.exercises.map((ex) => {
    const name = ex[location] || ex.gym;
    let setsCount = ex.baseSets;
    let restSec = ex.restSec;
    let technique = null;
    let rpeLabel = 'RPE 8';

    if (level === 'beginner') {
      setsCount = Math.max(2, Math.min(3, ex.baseSets - 1));
      restSec = Math.max(60, ex.restSec);
      rpeLabel = 'RPE 7 · Técnica Limpa';
    } else if (level === 'intermediate') {
      setsCount = ex.baseSets;
      rpeLabel = 'RPE 8–9 · Sobrecarga';
    } else if (level === 'pro') {
      rpeLabel = 'RPE 9–10';
      technique = ex.proTechnique || 'Rest-Pause / Drop-Set';
      if (ex.isFst7Finisher) {
        setsCount = 7;
        restSec = 35;
      } else {
        setsCount = ex.baseSets;
        restSec = Math.max(45, Math.round(ex.restSec * 0.9));
      }
    }

    // Buscar última carga registrada para esse exercício (ou baseline ajustada por local/nível)
    const historyEntries = loadHistory[name] || loadHistory[ex.gym] || [];
    const lastRecorded = historyEntries.length > 0 ? historyEntries[historyEntries.length - 1].weightKg : null;
    const prLoad = historyEntries.length > 0 ? Math.max(...historyEntries.map((h) => Number(h.weightKg) || 0)) : 0;

    let initialLoad = lastRecorded !== null ? lastRecorded : ex.defaultLoad;
    if (lastRecorded === null) {
      if (location === 'home') initialLoad = Math.round(initialLoad * 0.35);
      if (level === 'beginner') initialLoad = Math.round(initialLoad * 0.65);
      if (level === 'pro') initialLoad = Math.round(initialLoad * 1.15);
    }

    return {
      id: `${matrix.id}_${day.code}_${ex.id}`,
      baseId: ex.id,
      name,
      muscle: ex.muscle,
      reps: ex.reps,
      restSec,
      rpeLabel,
      technique,
      isFst7: level === 'pro' && Boolean(ex.isFst7Finisher),
      loadKg: Math.max(0, initialLoad),
      prKg: prLoad,
      sets: Array.from({ length: setsCount }, (_, idx) => ({
        index: idx + 1,
        done: false,
      })),
    };
  });

  return {
    id: `${matrix.id}_${day.code}_${location}_${level}`,
    source: 'matrix',
    matrixId: matrix.id,
    matrixName: matrix.name,
    mentors: matrix.mentors,
    dayCode: day.code,
    title: `Treino ${day.code} — ${day.title}`,
    focus: day.focus,
    location,
    level,
    exercises,
  };
}

/**
 * Converte um treino personalizado salvo pelo usuário para o formato executável
 */
export function buildCustomWorkoutSession(customWorkout, level = 'intermediate', loadHistory = {}) {
  const exercises = (customWorkout.exercises || []).map((ex, idx) => {
    const historyEntries = loadHistory[ex.name] || [];
    const lastRecorded = historyEntries.length > 0 ? historyEntries[historyEntries.length - 1].weightKg : null;
    const prLoad = historyEntries.length > 0 ? Math.max(...historyEntries.map((h) => Number(h.weightKg) || 0)) : 0;

    const isFst7 = ex.technique === 'FST-7';
    const setsCount = isFst7 ? 7 : Math.max(1, Number(ex.sets) || 3);

    return {
      id: `custom_${customWorkout.id}_${idx}`,
      baseId: ex.id || `custom_ex_${idx}`,
      name: ex.name,
      muscle: ex.muscle || 'Geral',
      reps: ex.reps || '10–12',
      restSec: isFst7 ? 35 : Number(ex.restSec) || 75,
      rpeLabel: level === 'pro' ? 'RPE 9–10' : level === 'intermediate' ? 'RPE 8–9' : 'RPE 7',
      technique: ex.technique || (level === 'pro' ? 'Rest-Pause / Drop-Set' : null),
      isFst7,
      loadKg: lastRecorded !== null ? lastRecorded : Number(ex.loadKg) || 0,
      prKg: prLoad,
      sets: Array.from({ length: setsCount }, (_, sIdx) => ({
        index: sIdx + 1,
        done: false,
      })),
    };
  });

  return {
    id: `custom_${customWorkout.id}`,
    source: 'custom',
    customId: customWorkout.id,
    matrixName: 'Treino Personalizado',
    mentors: customWorkout.focus || 'Criado pelo Atleta',
    dayCode: 'PRO',
    title: customWorkout.name,
    focus: customWorkout.focus || 'Protocolo sob medida',
    location: customWorkout.location || 'gym',
    level,
    exercises,
  };
}
